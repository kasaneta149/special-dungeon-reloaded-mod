	public static final EntityDataAccessor<Integer> ANIM = SynchedEntityData.defineId(BuschairEntity.class, EntityDataSerializers.INT);

	public BuschairEntity(EntityType<BuschairEntity> type, Level world) {
		super(type, world);
		xpReward = 0;
		setNoAi(true);
		setPersistenceRequired();
		this.setPathfindingMalus(PathType.WATER, 0);
		this.moveControl = new MoveControl(this) {
			@Override
			public void tick() {
				if (BuschairEntity.this.isInWater())
					BuschairEntity.this.setDeltaMovement(BuschairEntity.this.getDeltaMovement().add(0, 0.005, 0));
				if (this.operation == MoveControl.Operation.MOVE_TO && !BuschairEntity.this.getNavigation().isDone()) {
					double dx = this.wantedX - BuschairEntity.this.getX();
					double dy = this.wantedY - BuschairEntity.this.getY();
					double dz = this.wantedZ - BuschairEntity.this.getZ();
					float f = (float) (Mth.atan2(dz, dx) * (double) (180 / Math.PI)) - 90;
					float f1 = (float) (this.speedModifier * BuschairEntity.this.getAttribute(Attributes.MOVEMENT_SPEED).getValue());
					BuschairEntity.this.setYRot(this.rotlerp(BuschairEntity.this.getYRot(), f, 10));
					BuschairEntity.this.yBodyRot = BuschairEntity.this.getYRot();
					BuschairEntity.this.yHeadRot = BuschairEntity.this.getYRot();
					if (BuschairEntity.this.isInWater()) {
						BuschairEntity.this.setSpeed((float) BuschairEntity.this.getAttribute(Attributes.MOVEMENT_SPEED).getValue());
						float f2 = -(float) (Mth.atan2(dy, (float) Math.sqrt(dx * dx + dz * dz)) * (180 / Math.PI));
						f2 = Mth.clamp(Mth.wrapDegrees(f2), -85, 85);
						BuschairEntity.this.setXRot(this.rotlerp(BuschairEntity.this.getXRot(), f2, 5));
						float f3 = Mth.cos(BuschairEntity.this.getXRot() * (float) (Math.PI / 180.0));
						BuschairEntity.this.setZza(f3 * f1);
						BuschairEntity.this.setYya((float) (f1 * dy));
					} else {
						BuschairEntity.this.setSpeed(f1 * 0.05F);
					}
				} else {
					BuschairEntity.this.setSpeed(0);
					BuschairEntity.this.setYya(0);
					BuschairEntity.this.setZza(0);
				}
			}
		};
		refreshDimensions();
	}

